  const store = {
    get() { return localStorage.getItem('hapa_lang'); },
    set(v) { localStorage.setItem('hapa_lang', v); },
  };
  let lang = store.get() || (navigator.language && navigator.language.startsWith('ar') ? 'ar' : 'en');

  const I18N = {
    get lang() { return lang; },
    get dir() { return lang === 'ar' ? 'rtl' : 'ltr'; },
    t(key, vars) {
      let s = (DICT[lang] && DICT[lang][key]) || (DICT.en[key]) || key;
      if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
      return s;
    },
    apply(root) {
      const scope = root || document;
      scope.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = I18N.t(el.getAttribute('data-i18n')); });
      scope.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', I18N.t(el.getAttribute('data-i18n-ph'))); });
      const html = document.documentElement;
      html.lang = lang;
      html.dir = I18N.dir;
      const lb = document.getElementById('langBtnText');
      if (lb) lb.textContent = lang === 'ar' ? 'English' : 'العربية';
    },
    toggle() {
      lang = lang === 'ar' ? 'en' : 'ar';
      store.set(lang);
      I18N.apply();
      if (window.__onLangChange) window.__onLangChange();
    },
    fmtDate(iso) {
      if (!iso) return '—';
      // server stores UTC "YYYY-MM-DD HH:MM:SS"
      const s = String(iso).includes('T') ? iso : iso.replace(' ', 'T') + 'Z';
      const d = new Date(s);
      if (isNaN(d)) return iso;
      return new Intl.DateTimeFormat(lang === 'ar' ? 'ar-EG' : 'en-GB', {
        year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit',
      }).format(d);
    },
    fmtSize(b) {
      b = Number(b) || 0;
      if (b < 1024) return b + ' B';
      const u = ['KB', 'MB', 'GB'];
      let i = -1, v = b;
      do { v /= 1024; i++; } while (v >= 1024 && i < u.length - 1);
      return v.toFixed(v >= 100 ? 0 : 1) + ' ' + u[i];
    },
  };
  window.I18N = I18N;
